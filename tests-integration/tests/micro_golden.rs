//! Suite 10 — Micro QR golden vectors from independent implementations.
//!
//! Every other micro suite in this workspace is self-consistency: our encoder
//! feeding our decoder. That is exactly the shape of test that cannot catch a
//! convention error, and in KG-12 it did not — both crates agreed with each
//! other and with nobody else on how the 4-bit final data codeword of M1 and M3
//! is widened to a byte for Reed-Solomon (ISO 7.4.11 gives the width, 7.5.2 the
//! byte-wise arithmetic, and the standard settles nothing in between). The
//! interoperable convention is left-justified, `nibble << 4`; see
//! `handoff/REVIEW-REQUEST-interop.md`.
//!
//! So this suite has no round trip in it. The module grids below were produced
//! by implementations that share no code with ours:
//!
//! * **segno 1.6.6** (pure Python) generated every vector;
//! * **zxing-cpp 3.1.1** (C++) read every vector back to its payload, and for
//!   three of them its own encoder emitted a byte-identical grid.
//!
//! Both directions are asserted against those grids: our decoder must read them,
//! and our encoder must reproduce them module for module. Four of the seven are
//! marked *discriminating* — their half codeword is non-zero, so the two
//! widening readings give different error correction codewords and a different
//! symbol. The other three are controls that pass under either reading and exist
//! to prove the fixtures themselves are sound.
//!
//! Regenerated by `_temp/interop-kg12/gen_golden.py` if these ever need to move.

use qr_core::BitMatrix;
use qr_core::micro::{
    MicroEcLevel, MicroVersion, micro_data_modules, micro_mask_bit, micro_symbol_info,
};
use qr_decode::micro::decode_micro;
use qr_encode::micro::{MicroOptions, encode_micro};

/// One externally-produced symbol: the payload it carries and the exact module
/// grid an independent encoder emitted for it.
struct Vector {
    payload: &'static [u8],
    version: MicroVersion,
    ec: MicroEcLevel,
    mask: u8,
    /// Row-major, `'1'` dark, one string per row, top row first.
    modules: &'static [&'static str],
}

impl Vector {
    /// The vector's grid as a [`BitMatrix`].
    fn matrix(&self) -> BitMatrix {
        let size = self.modules.len() as u32;
        let mut m = BitMatrix::new(size);
        for (y, row) in self.modules.iter().enumerate() {
            assert_eq!(row.len() as u32, size, "vector is not square");
            for (x, c) in row.bytes().enumerate() {
                m.set(x as u32, y as u32, c == b'1');
            }
        }
        m
    }

    fn label(&self) -> String {
        format!(
            "{:?}-{:?} mask {} {:?}",
            self.version,
            self.ec,
            self.mask,
            core::str::from_utf8(self.payload).unwrap_or("<binary>")
        )
    }
}

