/// The four whose half codeword is non-zero, so the symbol they describe is
/// only produced by the left-justified widening. These are the vectors that
/// actually pin the convention; the rest would pass either way.
const DISCRIMINATING: &[&Vector] = &[&M1_12345, &M1_98765, &M3L_NUMERIC, &M3M_ALNUM];

// -- reference -> ours -------------------------------------------------------

/// Our decoder must read a symbol built by segno and validated by zxing-cpp,
/// with no error correction spent: these grids are pristine, so a non-zero
/// `errors_corrected` would mean we had silently "repaired" a correct symbol.
#[test]
fn decodes_every_external_vector() {
    for v in ALL {
        let decoded = decode_micro(&v.matrix())
            .unwrap_or_else(|e| panic!("{}: external vector must decode: {e:?}", v.label()));

        assert_eq!(decoded.bytes, v.payload, "{}: payload", v.label());
        assert_eq!(decoded.version, v.version, "{}: version", v.label());
        assert_eq!(decoded.ec, v.ec, "{}: error correction level", v.label());
        assert_eq!(decoded.mask, v.mask, "{}: mask", v.label());
        assert_eq!(
            decoded.errors_corrected,
            0,
            "{}: an undamaged symbol must need no correction",
            v.label()
        );
    }
}

// -- ours -> reference -------------------------------------------------------

/// Our encoder must reproduce each external grid exactly. Version, level and
/// mask are all forced, so the only freedom left is the encoding itself: mode
/// selection, character count, terminator, padding, Reed-Solomon, placement and
/// masking. Any disagreement anywhere in that chain shows up here as a module
/// difference.
#[test]
fn reproduces_every_external_vector() {
    for v in ALL {
        let mut opts = MicroOptions::new(v.ec);
        opts.version = Some(v.version);
        opts.mask = Some(v.mask);

        let ours = encode_micro(v.payload, opts)
            .unwrap_or_else(|e| panic!("{}: must encode: {e:?}", v.label()));
        let want = v.matrix();

        assert_eq!(ours.size(), want.size(), "{}: symbol size", v.label());
        let differing: Vec<(u32, u32)> = (0..want.size())
            .flat_map(|y| (0..want.size()).map(move |x| (x, y)))
            .filter(|&(x, y)| ours.get(x, y) != want.get(x, y))
            .collect();
        assert!(
            differing.is_empty(),
            "{}: {} modules differ from the external encoder, first at {:?}",
            v.label(),
            differing.len(),
            differing[0]
        );
    }
}

// -- the convention itself ---------------------------------------------------

/// Guards the guard: a vector only pins the half-codeword convention if its
/// final data codeword is non-zero, and it is easy to "fix" a failing fixture
/// by swapping in a payload that no longer discriminates. M1 needs five digits
/// and M3 needs a payload that fills the symbol; anything shorter pads the half
/// codeword to `0000`, where both widenings agree.
///
/// This reads the half codeword straight out of the grid — the last four data
/// modules in placement order, unmasked — and asserts it is non-zero. That is
/// precisely the condition under which `nibble << 4` and `nibble` are different
/// bytes, hence different error correction codewords, hence a different symbol.
#[test]
fn discriminating_vectors_really_discriminate() {
    for v in DISCRIMINATING {
        assert!(
            matches!(v.version, MicroVersion::M1 | MicroVersion::M3),
            "{}: only M1 and M3 have a half final data codeword",
            v.label()
        );

        let info =
            micro_symbol_info(v.version, v.ec).expect("the version offers this correction level");
        assert!(
            info.has_half_final_data_codeword(),
            "{}: expected a half final data codeword",
            v.label()
        );

        // The half codeword is the last four bits of the data region, so the
        // last four data modules the placement walk visits before the error
        // correction codewords begin.
        let order: Vec<(u32, u32)> = micro_data_modules(v.version).collect();
        let end = info.data_bits as usize;
        let matrix = v.matrix();
        let nibble = order[end - 4..end].iter().fold(0u8, |acc, &(x, y)| {
            (acc << 1) | u8::from(matrix.get(x, y) ^ micro_mask_bit(v.mask, x, y))
        });

        assert_ne!(
            nibble,
            0,
            "{}: half codeword is 0000, so this vector cannot tell the two \
             widening conventions apart and does not belong in DISCRIMINATING",
            v.label()
        );
    }
}
